#!/usr/bin/env python3
"""Generate src/vk_alloc_table.h from Khronos vk.xml.

For each Vulkan command taking `const VkAllocationCallbacks* pAllocator`,
records the 0-based argument index. The bionic bridge (src/elf_loader.c)
uses it to swap guest allocator callbacks for reverse thunks.

Usage: tools/gen_vk_alloc_table.py vk.xml > src/vk_alloc_table.h
"""
import sys
import xml.etree.ElementTree as ET

root = ET.parse(sys.argv[1]).getroot()
cmds = {}
aliases = {}
for c in root.find("commands"):
    if c.get("alias"):
        aliases[c.get("name")] = c.get("alias")
        continue
    name = c.find("proto/name").text
    if c.get("api") == "vulkansc":
        continue
    for i, p in enumerate(c.findall("param")):
        if p.get("api") == "vulkansc":
            continue
        t = p.find("type")
        if t is not None and t.text == "VkAllocationCallbacks":
            cmds[name] = i
            break
for a, target in aliases.items():
    if target in cmds:
        cmds[a] = cmds[target]
print("/* Generated by tools/gen_vk_alloc_table.py from vk.xml - do not edit. */")
print("static const struct { const char *name; unsigned char idx; } vk_alloc_table[] = {")
for n in sorted(cmds):
    print(f'    {{"{n}", {cmds[n]}}},')
print("};")
